class OfflineLLM:
    def __init__(self):
        self._used: set[str] = set()
        self._by_stem: dict[str, tuple[str, dict]] = {}

    def _next(self, item_type: str, descriptor: dict) -> dict:
        """An unused pool entry, preferring the same competence, then the same area."""
        pool = SJT_POOL if item_type == "sjt" else PRACTICAL_POOL
        fresh = [e for e in pool if e["stem"] not in self._used] or pool
        area_of = {c["code"]: a["id"] for a in FRAMEWORK["areas"] for c in a["competences"]}
        entry = min(fresh, key=lambda e: (e["competence"] != descriptor["competence"],
                                          area_of[e["competence"]] != descriptor["area"]))
        self._used.add(entry["stem"])
        self._by_stem[entry["stem"]] = (item_type, entry)
        return entry

    def _written(self, item_type: str, descriptor: dict) -> dict:
        e = self._next(item_type, descriptor)
        if item_type == "sjt":
            return {"stem": e["stem"], "artifact": None, "question": "Как вы поступите?", "correct_answer": e["correct"],
                    "correct_value": None, "key_rationale": f"{e['rationale']} ({descriptor['competence']}, {descriptor['target_level']})"}
        text, value = e["correct"]
        return {"stem": e["stem"], "artifact": e["artifact"], "question": e["question"], "correct_answer": text,
                "correct_value": value,
                "key_rationale": f"Ответ однозначно вычисляется по таблице ({descriptor['competence']}, {descriptor['target_level']})."}

    async def complete(self, request: LLMRequest, timeout: float) -> LLMResponse:
        return LLMResponse(text=json.dumps(getattr(self, f"_{request.task}")(request.payload), ensure_ascii=False))

    def _choose_cells(self, p: dict) -> dict:
        cells = []
        for z in p["zones"]:
            comp = min(z["competences"], key=lambda c: c["self_score_0_4"])
            practical = "practical" in z["allowed_item_types"] and z["area"] == 4
            kind = "практическое задание проверит работу с данными" if practical else "кейс проверит действия в типичной ситуации"
            cells.append({"area": z["area"], "competence": comp["code"], "item_type": "practical" if practical else "sjt",
                          "rationale": f"Самая низкая самооценка в области — {comp['code']} ({comp['self_score_0_4']} из 4); {kind}."})
        return {"cells": cells}

    def _write_items(self, p: dict) -> dict:
        return {"items": [self._written(p["item_type"], p["descriptor"]) for _ in range(p["count"])]}

    def _revise_item(self, p: dict) -> dict:
        return self._written(p["item_type"], p["descriptor"])

    def _design_distractors(self, p: dict) -> dict:
        out = []
        for item in p["items"]:
            kind, e = self._by_stem[item["stem"]]
            if kind == "sjt":
                ds = [{"text": t, "value": None, "feedback": f, "misconception": m} for t, f, m in e["distractors"]]
                fb = e["correct_feedback"]
            else:
                ds = [{"text": t, "value": v, "feedback": f"Неверно: {m.lower()}", "misconception": m} for t, v, m in e["distractors"]]
                fb = "Верно: ответ получен точным расчётом по таблице."
            out.append({"item_id": item["item_id"], "correct_feedback": fb, "distractors": ds})
        return {"items": out}

    def _blind_solve(self, p: dict) -> dict:
        out = []
        for item in p["items"]:
            kind, e = self._by_stem[item["stem"]]
            correct_text = e["correct"] if kind == "sjt" else e["correct"][0]
            answer = next(o["id"] for o in item["options"] if o["text"] == correct_text)
            out.append({"item_id": item["item_id"], "answer": answer, "confidence": 0.9, "defensible_alternatives": [],
                        "blocking_issues": [], "python_code": e.get("code")})
        return {"items": out}

    def _review_alignment(self, p: dict) -> dict:
        return {"items": [{"item_id": i["item_id"], "competence_match": True, "level_match": True,
                           "requires_competence": True, "solvable_by": None, "issues": []} for i in p["items"]]}
